def write_files(repo_root: Path):
    for rel, b64 in FILES.items():
        target = repo_root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(base64.b64decode(b64))
        print(f"  wrote {rel}")


def patch_workspace_cargo_toml(repo_root: Path):
    cargo_toml = repo_root / "Cargo.toml"
    if not cargo_toml.exists():
        print("!! No Cargo.toml at repo root - skipping workspace member patch")
        return

    text = cargo_toml.read_text()

    if '"wie_jni"' in text:
        print("Cargo.toml: wie_jni already a workspace member, skipping")
        return

    marker = '    "wie_skt",\n]'
    if marker not in text:
        print("!! Could not find expected `members = [...]` tail in Cargo.toml.")
        print('   Add "wie_jni" to the workspace `members` list by hand.')
        return

    text = text.replace(marker, '    "wie_skt",\n    "wie_jni",\n]')
    cargo_toml.write_text(text)
    print("Cargo.toml: added wie_jni to workspace members")


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)

    repo_root = Path(sys.argv[1]).resolve()
    if not (repo_root / "Cargo.toml").exists():
        print(f"!! {repo_root} doesn't look like the wie repo root (no Cargo.toml)")
        sys.exit(1)

    print(f"Applying android support to {repo_root}")
    write_files(repo_root)
    patch_workspace_cargo_toml(repo_root)

    print()
    print("Done. Next steps:")
    print("  1. rustup target add aarch64-linux-android armv7-linux-androideabi")
    print("  2. cargo install cargo-ndk")
    print("  3. export ANDROID_NDK_HOME=/path/to/ndk")
    print("  4. cd android && gradle assembleDebug   (or push and let CI build it)")
    print()
    print("First launch on-device: grant \"All files access\" when prompted")
    print("(needed to write /storage/emulated/0/wie/wie_jni.log), then relaunch")
    print("the app once so the log file actually opens.")


if __name__ == "__main__":
    main()
